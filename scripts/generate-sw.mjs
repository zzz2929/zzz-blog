// 生成 Service Worker:预缓存 dist/client 全部页面与核心资源(含 pagefind 搜索索引)
// 由 scripts/build.mjs 在 astro build 之后调用
//
// 手写实现(零依赖):不再使用 workbox-build —— 该包依赖 babel/rollup/terser 等
// 重型依赖树,仅模块加载就要 ~8s;手写版直接用 node 内置模块扫描产物并生成
// 等价行为的 sw.js(预缓存 + revision 版本化 + 图片 StaleWhileRevalidate),
// 整个步骤降到 ~1s。
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const clientDir = join(__dirname, '..', 'dist', 'client');

// 站点名/作者来自 src/config/site.ts(Node ≥22.18 原生支持导入 TS,旧版回退正则)
async function loadSiteMeta() {
  try {
    const { siteConfig } = await import('../src/config/site.ts');
    return { title: siteConfig.title, author: siteConfig.author };
  } catch {
    const src = readFileSync(join(__dirname, '..', 'src/config/site.ts'), 'utf-8');
    return {
      title: src.match(/title:\s*"([^"]+)"/)?.[1] || 'Blog',
      author: src.match(/author:\s*"([^"]+)"/)?.[1] || '',
    };
  }
}

// manifest.webmanifest(PWA 可安装清单;图标由 generate-icons.mjs 生成)
// 先写入产物目录,后续预缓存扫描才能包含它
const SITE = await loadSiteMeta();
const manifest = {
  name: SITE.title,
  short_name: SITE.title,
  start_url: '/',
  display: 'standalone',
  theme_color: '#425AEF',
  background_color: '#EDE8DE',
  icons: [
    { src: '/icons/pwa-192.png', sizes: '192x192', type: 'image/png' },
    { src: '/icons/pwa-512.png', sizes: '512x512', type: 'image/png' },
    { src: '/icons/pwa-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
writeFileSync(join(clientDir, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

// ---- 预缓存清单收集(替代 workbox glob) ----
// 规则与原 workbox globPatterns 一致:html / js / css / svg / favicon / robots /
// manifest / og 图 / fonts / pagefind;图片(webp/png/jpg/gif/avif)走运行时 SWR,
// 不预缓存;排除 sourcemap 与 sw 自身。
const IGNORE_RULES = [
  /\.map$/,
  /^sw\.js$/,
  /^_astro\/.+\.(webp|png|jpe?g|gif|avif)$/i,
];

const INCLUDE_RULES = [
  /\.html$/,
  /\.(js|css)$/i,
  /\.svg$/,
  /^(favicon\.ico|favicon\.png|robots\.txt|manifest\.webmanifest)$/,
  /^og\/posts\/.+\.png$/,
  /^fonts\//,
  /^pagefind\//,
];

function collectEntries(dir = clientDir, prefix = '', out = []) {
  for (const entry of readdirSync(join(dir, prefix), { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    const full = join(dir, rel);
    if (entry.isDirectory()) collectEntries(dir, rel, out);
    else if (entry.isFile()) {
      if (IGNORE_RULES.some((re) => re.test(rel))) continue;
      if (!INCLUDE_RULES.some((re) => re.test(rel))) continue;
      // revision:内容 md5(与 workbox 相同);URL 路径做百分号编码,
      // 与浏览器 new URL().pathname 的规范化形式保持一致(中文路径关键)
      const pathname = '/' + rel.split(sep).join('/');
      const url = encodeURI(pathname);
      const revision = createHash('md5').update(readFileSync(full)).digest('hex');
      out.push({ url, revision });
    }
  }
  return out;
}

const PRECACHE = collectEntries();

// url → 带 revision 的版本化缓存 key(install 时按此 key 写入,activate 按此清理)
const MAP = {};
for (const { url, revision } of PRECACHE) {
  MAP[url] = `${url}?__WB_REVISION__=${revision}`;
}

const swSource = `// Generated by scripts/generate-sw.mjs (zero-dependency build-time SW)
const PRECACHE = ${JSON.stringify(PRECACHE)};
const MAP = ${JSON.stringify(MAP)};
const CACHE = 'blog-precache-v1';
const IMG_CACHE_LOCAL = 'blog-images';
const IMG_CACHE_REMOTE = 'imgbed-images';
const IMG_RE = /\\.(webp|png|jpe?g|gif|avif)$/i;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(PRECACHE.map(async ({ url, revision }) => {
      const key = url + '?__WB_REVISION__=' + revision;
      if (await cache.match(key)) return; // 同版本已缓存,跳过(增量更新)
      const res = await fetch(key);
      if (res && res.ok) await cache.put(key, res);
    }));
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // 清理本缓存中已不在当前 manifest 的旧版本条目
    const valid = new Set(Object.values(MAP));
    const cache = await caches.open(CACHE);
    for (const req of await cache.keys()) {
      if (!valid.has(req.url)) await cache.delete(req);
    }
    // 清理历史 workbox 生成的预缓存(升级路径)
    for (const name of await caches.keys()) {
      if (name.startsWith('workbox-precache-') || name === 'blog-precache-v0') {
        await caches.delete(name);
      }
    }
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

async function staleWhileRevalidate(request, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(request);
  const network = fetch(request).then((response) => {
    if (response && response.ok) cache.put(request, response.clone());
    return response;
  }).catch(() => hit);
  return hit || network;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) {
    // 跨域:仅图床图片走 StaleWhileRevalidate
    if (/^https:\\/\\/imgbed\\.904002\\.xyz\\//.test(request.url)) {
      event.respondWith(staleWhileRevalidate(request, IMG_CACHE_REMOTE));
    }
    return;
  }
  const pathname = url.pathname;
  // 预缓存命中(含目录/无扩展名导航 → index.html / .html 的 cleanURLs 映射)
  const precacheKey =
    MAP[pathname] ||
    (pathname.endsWith('/') && MAP[pathname + 'index.html']) ||
    MAP[pathname + '.html'];
  if (precacheKey) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const hit = await cache.match(precacheKey);
      return hit || fetch(request);
    })());
    return;
  }
  // 本域图片:StaleWhileRevalidate
  if (IMG_RE.test(pathname)) {
    event.respondWith(staleWhileRevalidate(request, IMG_CACHE_LOCAL));
  }
});
`;

writeFileSync(join(clientDir, 'sw.js'), swSource);

console.log(`[sw] Service Worker 生成完成(预缓存 ${PRECACHE.length} 个条目) → dist/client/sw.js`);
